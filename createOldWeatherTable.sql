USE STAGING;

DROP TABLE IF EXISTS WEATHER_PROCESSED_T;

CREATE TABLE WEATHER_PROCESSED_T
(
    I          VARCHAR(16),
    NAME       VARCHAR(255),
    LAT        DECIMAL(9, 6),
    LON        DECIMAL(9, 6),
    COUNTRY    VARCHAR(100),
    CONTINENT  VARCHAR(100),
    ELEVATION  DECIMAL(9, 2),
    DAYKEY     DATE,
    HOURKEY    DECIMAL(4, 1),
    METRIC     VARCHAR(16),
    VALUE    VARCHAR(255),
    year     SMALLINT,
    MONTH    VARCHAR(2),
    DAY      VARCHAR(2),
    DT         DATE
) ENGINE=InnoDB
  DEFAULT CHARACTER SET=UTF8MB4;
