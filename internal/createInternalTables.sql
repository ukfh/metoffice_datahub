USE STAGING;

CREATE TABLE IF NOT EXISTS INTERNAL_TEMPERATURE_TMP
(
    EPOCH            BIGINT UNSIGNED NOT NULL,
    T_I              DECIMAL(5, 2) NOT NULL,
    H_I              DECIMAL(5, 2) NOT NULL,
    MYSTERY          TINYINT UNSIGNED NOT NULL,
    DT               CHAR(10) NOT NULL,
    `TIME`           TIME NOT NULL,
    DEW_POINT        DECIMAL(5, 2) NOT NULL,
    WATER_CONTENT    DECIMAL(5, 2) NOT NULL,
    FILENAME         VARCHAR(255) NULL,
    REC_LOAD_DT      DATETIME NULL,
    REC_LOAD_EPOCH   BIGINT UNSIGNED NULL
) ENGINE=InnoDB
  DEFAULT CHARACTER SET=utf8mb4;

CREATE TABLE IF NOT EXISTS INTERNAL_TEMPERATURE
(
    EPOCH            BIGINT UNSIGNED NOT NULL,
    T_I              DECIMAL(5, 2) NOT NULL,
    H_I              DECIMAL(5, 2) NOT NULL,
    MYSTERY          TINYINT UNSIGNED NOT NULL,
    DT               CHAR(10) NOT NULL,
    `TIME`           TIME NOT NULL,
    DEW_POINT        DECIMAL(5, 2) NOT NULL,
    WATER_CONTENT    DECIMAL(5, 2) NOT NULL,
    FILENAME         VARCHAR(255) NOT NULL,
    REC_LOAD_DT      DATETIME NOT NULL,
    REC_LOAD_EPOCH   BIGINT UNSIGNED NOT NULL,
    REC_ADDED_DT     DATETIME NOT NULL,
    PRIMARY KEY (EPOCH)
) ENGINE=InnoDB
  DEFAULT CHARACTER SET=utf8mb4;

